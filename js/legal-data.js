window.renderLegal = function (docId) {
  var doc = LEGAL_DATA[docId];
  if (!doc) return;
  var el = document.getElementById(docId);
  var html = "";
  doc.sections.forEach(function (sec) {
    html += "<h2>" + sec.heading + "</h2>";
    sec.body.forEach(function (item) {
      if (Array.isArray(item)) {
        html += "<ul>";
        item.forEach(function (li) {
          html += "<li>" + li + "</li>";
        });
        html += "</ul>";
      } else {
        html += "<p>" + item + "</p>";
      }
    });
  });
  html += '<p class="brand-line">' + doc.brand + '<br>Website: mccombat.net</p>';
  el.innerHTML = html;
};
